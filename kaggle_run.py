#!/usr/bin/env python3
"""Run this repo's GPU checks on a Kaggle T4 from the command line.

The development machine has no CUDA GPU. This script packs every kernel module into one
generated Kaggle script, pushes it with the Kaggle CLI, waits for the run, downloads the
result file and prints it. The exit status is 0 only if every command passed on the GPU.

Two things make a result trustworthy:
  - The generated script carries the git commit it was built from and whether the tree
    had uncommitted changes. Both are printed at the top of the result.
  - Every build has a fresh id. `run` accepts a downloaded result only if it carries the
    id it just pushed, so an earlier run's result is never mistaken for this one.

Needs the Kaggle CLI on PATH and a logged-in account:
    uv tool install kaggle --with six
    kaggle auth login

Usage: python kaggle_run.py run                 (math probe and checks, no benchmarks)
       python kaggle_run.py run --bench         (checks plus every benchmark)
       python kaggle_run.py run --cmd "python softmax_checks.py --no-compile"
       python kaggle_run.py run --internet --cmd "python -m pip install -q --target /tmp/t triton==3.8.0" \
           --cmd "PYTHONPATH=/tmp/t python probe_spills.py"      (same GPU, another Triton version)
       python kaggle_run.py build --out DIR     (write the kernel folder, push nothing)
       python kaggle_run.py status | logs | fetch
"""

from __future__ import annotations

import argparse
import base64
import json
import re
import shlex
import subprocess
import sys
import tempfile
import time
import uuid
from pathlib import Path

REPO = Path(__file__).resolve().parent

# The Kaggle kernel the runs go to. Kaggle derives the slug from the title, so the two
# must agree. The kernel is private.
KERNEL_ID = "terrellblash/triton-kernel-checks"
KERNEL_TITLE = "Triton kernel checks"
CODE_FILE = "triton_kernel_checks.py"
ACCELERATOR = "NvidiaTeslaT4"  # Kaggle's "GPU T4 x2"

RESULT_FILE = "results.txt"
PASS_LINE = "RESULT: PASS"

# Always the first command: without it a result cannot say which GPU and versions it used.
VERSION_PROBE = [
    "python",
    "-c",
    'import torch, triton; print("torch", torch.__version__, "| triton", triton.__version__, '
    '"|", torch.cuda.get_device_name(0), "x", torch.cuda.device_count())',
]
CHECK_SCRIPTS = ("layernorm_triton.py", "layernorm_bwd_checks.py", "softmax_checks.py")
# Runs before the checks: it measures the approximate-math budgets the bounds rely on, in seconds.
MATH_PROBE = ["python", "probe_math.py"]

POLL_SECONDS = 15
RUNNING_STATES = {"QUEUED", "RUNNING", "NEW_SCRIPT"}

# The script that runs on Kaggle. It unpacks the embedded modules into a temporary
# directory, runs each command there, and copies everything the commands print into
# results.txt. It always exits 0 so Kaggle keeps results.txt; the verdict is the RESULT line.
KERNEL_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by kaggle_run.py. Do not edit; change the repo and rebuild."""
import base64
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

PAYLOAD = json.loads(__PAYLOAD__)
ENV_ASSIGNMENT = re.compile("[A-Za-z_][A-Za-z0-9_]*=")


def main():
    src = Path(tempfile.mkdtemp(prefix="triton_src_"))
    for name, data in PAYLOAD["files"].items():
        (src / name).write_bytes(base64.b64decode(data))
    env = dict(os.environ, PYTHONUNBUFFERED="1")
    failed = []
    with open(PAYLOAD["result_file"], "w") as out:

        def emit(text):
            print(text, flush=True)
            out.write(text + "\\n")
            out.flush()

        emit("build " + PAYLOAD["build_id"])
        emit("commit " + PAYLOAD["commit"] + (" + uncommitted changes" if PAYLOAD["dirty"] else ""))
        for cmd in PAYLOAD["commands"]:
            shown = shlex.join(cmd)
            emit("$ " + shown)
            cmd_env = dict(env)
            while cmd and ENV_ASSIGNMENT.match(cmd[0]):
                name, _, value = cmd[0].partition("=")
                cmd_env[name] = value
                cmd = cmd[1:]
            if not cmd:
                emit("nothing to run after the environment assignments")
                failed.append(shown)
                continue
            argv = [sys.executable if cmd[0] == "python" else cmd[0], *cmd[1:]]
            try:
                proc = subprocess.Popen(
                    argv, cwd=src, env=cmd_env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
                )
            except OSError as exc:
                emit("could not start: " + str(exc))
                failed.append(shown)
                continue
            for line in proc.stdout:
                emit(line.rstrip("\\n"))
            code = proc.wait()
            emit("[exit " + str(code) + "]")
            if code != 0:
                failed.append(shown)
        emit("RESULT: FAIL: " + "; ".join(failed) if failed else "RESULT: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


class KaggleError(RuntimeError):
    """The Kaggle CLI failed, or a run did not produce a result this script can trust."""


def repo_sources() -> dict[str, bytes]:
    """Return every top-level module the kernels need, by file name.

    Returns:
        {name: contents} for each *.py in the repo root except this script.

    Raises:
        KaggleError: common.py is missing. Every check script imports it.
    """
    files = {p.name: p.read_bytes() for p in sorted(REPO.glob("*.py")) if p.name != Path(__file__).name}
    if "common.py" not in files:
        raise KaggleError(f"common.py not found in {REPO}; every check script imports it")
    return files


def git_state() -> tuple[str, bool]:
    """Return the commit the tree is on and whether any tracked or new file differs from it.

    Returns:
        (short commit hash, dirty). The hash is "unknown" outside a git checkout.
    """
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True, text=True, check=True
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain"], cwd=REPO, capture_output=True, text=True, check=True
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return "unknown", True
    return commit, bool(status.strip())


def default_commands(bench: bool) -> list[list[str]]:
    """Commands for a standard run: the math probe, then every check script, with benchmarks only if asked."""
    extra = [] if bench else ["--skip-bench"]
    return [MATH_PROBE, *(["python", script, *extra] for script in CHECK_SCRIPTS)]


def render_kernel(files: dict[str, bytes], commands: list[list[str]], commit: str, dirty: bool, build_id: str) -> str:
    """Return the source of the script that runs on Kaggle.

    Args:
        files: {name: contents} of the modules to unpack next to each other.
        commands: argument lists run in order from the unpacked directory. Leading
            NAME=value items set environment variables for that command, as in a shell.
            The first item after them, if it is "python", is replaced by the kernel's own
            interpreter.
        commit: git commit the files came from.
        dirty: True if the working tree differed from that commit.
        build_id: unique id for this build, echoed in the result.
    """
    payload = {
        "files": {name: base64.b64encode(data).decode("ascii") for name, data in files.items()},
        "commands": commands,
        "commit": commit,
        "dirty": dirty,
        "build_id": build_id,
        "result_file": RESULT_FILE,
    }
    return KERNEL_TEMPLATE.replace("__PAYLOAD__", repr(json.dumps(payload)))


def write_kernel_dir(out: Path, kernel_id: str, script: str, internet: bool = False) -> None:
    """Write the generated script and the kernel-metadata.json the Kaggle CLI pushes.

    Args:
        out: folder to write into; created if missing.
        kernel_id: "owner/slug" of the Kaggle kernel.
        script: source from render_kernel.
        internet: let the run reach the internet. Off unless a run has to download something.
    """
    out.mkdir(parents=True, exist_ok=True)
    (out / CODE_FILE).write_text(script, encoding="utf-8")
    metadata = {
        "id": kernel_id,
        "title": KERNEL_TITLE,
        "code_file": CODE_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": internet,
        "machine_shape": ACCELERATOR,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


def build(out: Path, kernel_id: str, commands: list[list[str]], internet: bool = False) -> str:
    """Write a kernel folder for the current tree and return its build id."""
    commit, dirty = git_state()
    build_id = f"{time.strftime('%Y%m%dT%H%M%S')}-{uuid.uuid4().hex[:8]}"
    script = render_kernel(repo_sources(), [VERSION_PROBE, *commands], commit, dirty, build_id)
    write_kernel_dir(out, kernel_id, script, internet)
    print(f"built {build_id} from commit {commit}{' + uncommitted changes' if dirty else ''} in {out}")
    return build_id


def kaggle(*args: str) -> str:
    """Run the Kaggle CLI and return what it printed.

    Raises:
        KaggleError: the CLI is not installed or exited non-zero. The message carries its output.
    """
    try:
        proc = subprocess.run(["kaggle", *args], capture_output=True, text=True, check=False)
    except FileNotFoundError as exc:
        raise KaggleError("kaggle CLI not found; install it with: uv tool install kaggle --with six") from exc
    output = (proc.stdout + proc.stderr).strip()
    if proc.returncode != 0:
        raise KaggleError(f"kaggle {' '.join(args)} failed (exit {proc.returncode}):\n{output}")
    return output


def kernel_status(kernel_id: str) -> str:
    """Return the state of the kernel's latest run, e.g. RUNNING, COMPLETE or ERROR.

    Raises:
        KaggleError: the CLI output has no status in the expected form.
    """
    output = kaggle("kernels", "status", kernel_id)
    match = re.search(r'has status "(?:KernelWorkerStatus\.)?(\w+)"', output)
    if not match:
        raise KaggleError(f"could not read a status from: {output}")
    return match.group(1).upper()


def fetch_result(kernel_id: str) -> str:
    """Download results.txt from the kernel's latest run and return its text.

    Raises:
        KaggleError: the run produced no results.txt.
    """
    with tempfile.TemporaryDirectory(prefix="kaggle_out_") as tmp:
        kaggle("kernels", "output", kernel_id, "-p", tmp, "--file-pattern", re.escape(RESULT_FILE) + "$", "-o", "-q")
        found = sorted(Path(tmp).rglob(RESULT_FILE))
        if not found:
            raise KaggleError(
                f"the latest run of {kernel_id} has no {RESULT_FILE}; see: kaggle kernels logs {kernel_id}"
            )
        return found[0].read_text(encoding="utf-8")


def wait_for_result(kernel_id: str, build_id: str, wait_minutes: float) -> str:
    """Poll until the run for `build_id` finishes, then return its result text.

    A finished state alone is not enough: right after a push the status can still describe
    the previous run. The result is accepted only if it carries `build_id`.

    Raises:
        KaggleError: the run errored, was cancelled, or did not finish in time.
    """
    deadline = time.monotonic() + wait_minutes * 60
    last = ""
    while time.monotonic() < deadline:
        state = kernel_status(kernel_id)
        if state != last:
            print(f"status: {state}", flush=True)
            last = state
        if state not in RUNNING_STATES:
            if state == "COMPLETE":
                text = fetch_result(kernel_id)
                if f"build {build_id}" in text:
                    return text
            else:
                raise KaggleError(f"run ended with status {state}; see: kaggle kernels logs {kernel_id}")
        time.sleep(POLL_SECONDS)
    raise KaggleError(f"no result for build {build_id} after {wait_minutes:g} minutes; last status {last or 'unknown'}")


def main() -> int:
    """Parse the command line and run one action.

    Returns:
        0 if the result says every command passed (or the action printed what was asked),
        1 if the result reports a failure, 2 if Kaggle or the run itself could not be used.
    """
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("action", choices=("run", "build", "status", "logs", "fetch"))
    parser.add_argument("--kernel", default=KERNEL_ID, help="Kaggle kernel as owner/slug")
    parser.add_argument("--bench", action="store_true", help="run the benchmarks too, not only the checks")
    parser.add_argument("--cmd", action="append", help="command to run instead of the standard set; repeatable")
    parser.add_argument("--internet", action="store_true", help="let the run download, e.g. another Triton version")
    parser.add_argument("--out", type=Path, help="build: folder to write the kernel into")
    parser.add_argument("--timeout", type=int, default=3600, help="run: Kaggle-side limit in seconds")
    parser.add_argument("--wait-minutes", type=float, default=45, help="run: how long to wait for the result")
    args = parser.parse_args()

    commands = [shlex.split(c) for c in args.cmd] if args.cmd else default_commands(args.bench)
    try:
        if args.action == "status":
            print(kernel_status(args.kernel))
            return 0
        if args.action == "logs":
            print(kaggle("kernels", "logs", args.kernel))
            return 0
        if args.action == "fetch":
            text = fetch_result(args.kernel)
        elif args.action == "build":
            if args.out is None:
                parser.error("build needs --out DIR")
            build(args.out, args.kernel, commands, args.internet)
            return 0
        else:
            with tempfile.TemporaryDirectory(prefix="kaggle_kernel_") as tmp:
                build_id = build(Path(tmp), args.kernel, commands, args.internet)
                print(kaggle("kernels", "push", "-p", tmp, "--accelerator", ACCELERATOR, "-t", str(args.timeout)))
            text = wait_for_result(args.kernel, build_id, args.wait_minutes)
    except KaggleError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(text, end="" if text.endswith("\n") else "\n")
    return 0 if PASS_LINE in text.splitlines() else 1


if __name__ == "__main__":
    sys.exit(main())
